#!/usr/bin/env python3
"""Run the reference solutions of practice problems in Python, Go, C++, Rust and Scala against their tests.

  python3 tools/check_langs.py [file] [--langs python,go,cpp,rust,scala] [--ids two-sum,lru-cache] [--starters]
                               [--jobs N] [--keep DIR] [--timeout S] [-v]

file      content/practice/problems.json (default), or a patch file content/drafts/practice_langs_K.json (a list of
          {id, sig, langs}; each entry is merged over the problem with that id in problems.json).
--langs   languages to check (default: all five). JavaScript is checked by node tools/check_practice.js.
--ids     only these problem ids.
--starters  also check that every starter compiles and runs (its tests may fail; it must not crash the program).
--keep    write the generated programs and binaries to DIR and keep them (default: a temporary folder, deleted).
-v        print every failing test.

Only problems with a "sig" and "langs" are checked. Each program is generated by tools/langharness.py (the same text the
app's "Copy test program" button gives a learner), run with --json, and must pass every test. Go builds every program
in one `go build ./...`; C++ shares a precompiled header; Rust and C++ compile in parallel (--jobs, default: CPU count).
When node is installed it also checks that web/langharness.js (used by the app) generates exactly the same programs.
A language whose toolchain is not installed (Scala here: scala-cli) is reported as "not checked", not as a failure.
Exit code 1 when anything fails. As a module: check(problems, langs, starters=False, ...) -> list of result dicts."""
import concurrent.futures as cf
import json, os, re, shutil, subprocess, sys, tempfile, time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import langharness as H

ALL = ["python", "go", "cpp", "rust", "scala"]


def tools():
    """The command for each language, or None when it is not installed."""
    sc = shutil.which("scala-cli") or None
    return {"python": sys.executable or shutil.which("python3"), "go": shutil.which("go"), "cpp": shutil.which("g++"), "rust": shutil.which("rustc"), "scala": sc}


def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def run(cmd, cwd=None, timeout=60, env=None):
    t0 = time.time()
    try:
        r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout, env=env)
        return r.returncode, r.stdout, r.stderr, time.time() - t0
    except subprocess.TimeoutExpired as e:
        out = e.stdout.decode("utf-8", "replace") if isinstance(e.stdout, bytes) else (e.stdout or "")
        return None, out, "timed out after %ss" % timeout, time.time() - t0


def parse_result(out):
    for line in reversed((out or "").splitlines()):
        if line.startswith("DTS-RESULT "):
            try:
                return json.loads(line[len("DTS-RESULT "):])
            except ValueError:
                return None
    return None


def short(text, n=25):
    lines = [l for l in (text or "").splitlines() if l.strip()]
    return "\n".join(lines[:n]) + ("\n..." if len(lines) > n else "")


def check(problems, langs=ALL, starters=False, jobs=None, keep=None, timeout=10, log=print):
    """Generate, build and run. Returns [{id, lang, kind ('solution'|'starter'), status, detail, passed, total}], where status is
    ok | fail | compile | timeout | crash | sig | missing | unchecked."""
    have = tools()
    jobs = jobs or os.cpu_count() or 2
    work = os.path.abspath(keep) if keep else tempfile.mkdtemp(prefix="dts_langs_")
    os.makedirs(work, exist_ok=True)
    results, jobsl = [], []          # jobsl: (key, problem, lang, kind, program text)
    for p in problems:
        try:
            H.prepare(p)
        except H.HarnessError as e:
            results.append(dict(id=p.get("id"), lang="-", kind="solution", status="sig", detail=str(e)))
            continue
        for lang in langs:
            code = (p.get("langs") or {}).get(lang) or {}
            for kind in (["solution", "starter"] if starters else ["solution"]):
                if not isinstance(code.get(kind), str) or not code[kind].strip():
                    results.append(dict(id=p["id"], lang=lang, kind=kind, status="missing", detail="no %s %s in langs.%s" % (lang, kind, lang)))
                    continue
                if not have[lang]:
                    results.append(dict(id=p["id"], lang=lang, kind=kind, status="unchecked", detail="%s is not installed" % {"scala": "scala-cli"}.get(lang, lang)))
                    continue
                key = "p%03d_%s_%s" % (len(jobsl), re.sub(r"[^a-z0-9]+", "_", p["id"]), kind[:3])
                jobsl.append((key, p, lang, kind, H.program(p, lang, code[kind])))

    def finish(job, rc, out, err, secs):
        key, p, lang, kind, _ = job
        r = dict(id=p["id"], lang=lang, kind=kind)
        res = parse_result(out)
        if rc is None:
            r.update(status="timeout", detail="no result within %ss (an infinite loop, or a very slow solution?)" % timeout)
        elif res is None:
            r.update(status="crash", detail="the program printed no result (exit code %s)\n%s" % (rc, short(err + "\n" + out)))
        elif res.get("error"):
            r.update(status="fail", detail=res["error"], passed=0, total=res.get("total"))
        else:
            r.update(passed=res["pass"], total=res["total"])
            if kind == "starter" or res["pass"] == res["total"]:
                r.update(status="ok", detail="")
            else:
                bad = [(i, x) for i, x in enumerate(res["results"]) if not x.get("ok")]
                tests = p["tests"]
                r.update(status="fail", detail="\n".join("test %d: input %s expected %s got %s" % (i + 1, json.dumps(tests[i]["args"])[:200], json.dumps(tests[i]["expected"])[:200],
                                                         ("error: " + x["error"]) if x.get("error") else x.get("got", "?")[:200]) for i, x in bad))
        results.append(r)

    def compiled(job, rc, out, err, exe):
        if rc != 0:
            key, p, lang, kind, _ = job
            results.append(dict(id=p["id"], lang=lang, kind=kind, status="compile", detail=short(err or out)))
            return None
        return exe

    by = {l: [j for j in jobsl if j[2] == l] for l in ALL}
    to_run = []                                                # (job, argv)
    for j in by["python"]:
        f = os.path.join(work, j[0] + ".py")
        write(f, j[4])
        to_run.append((j, [have["python"], f, "--json"]))
    if by["go"]:
        gd = os.path.join(work, "go")
        os.makedirs(os.path.join(gd, "bin"), exist_ok=True)
        write(os.path.join(gd, "go.mod"), "module dtscheck\n\ngo 1.21\n")
        for j in by["go"]:
            os.makedirs(os.path.join(gd, j[0]), exist_ok=True)
            write(os.path.join(gd, j[0], "main.go"), j[4])
        env = dict(os.environ, GOFLAGS="-mod=mod", GOTOOLCHAIN="local", GOPROXY="off", GOWORK="off")
        log("go: building %d programs" % len(by["go"]))
        rc, out, err, _ = run([have["go"], "build", "-o", "bin/", "./..."], cwd=gd, timeout=900, env=env)
        if rc == 0:
            to_run += [(j, [os.path.join(gd, "bin", j[0]), "--json"]) for j in by["go"]]
        else:   # find the broken ones: build each on its own (the build cache makes the good ones quick)
            with cf.ThreadPoolExecutor(jobs) as ex:
                futs = {ex.submit(run, [have["go"], "build", "-o", "bin/" + j[0], "./" + j[0]], gd, 300, env): j for j in by["go"]}
                for fu in cf.as_completed(futs):
                    j = futs[fu]
                    rc2, o2, e2, _ = fu.result()
                    exe = compiled(j, rc2, o2, e2, os.path.join(gd, "bin", j[0]))
                    if exe:
                        to_run.append((j, [exe, "--json"]))
    if by["cpp"]:
        cd = os.path.join(work, "cpp")
        os.makedirs(cd, exist_ok=True)
        flags = ["-std=c++17", "-O2"]
        pch = os.path.join(cd, "dts_pch.hpp")
        write(pch, "".join(l + "\n" for l in H.PRE["cpp_head"].splitlines() if l.startswith("#include")))
        rc, out, err, _ = run([have["cpp"]] + flags + ["-x", "c++-header", pch, "-o", pch + ".gch"], timeout=300)
        inc = ["-include", pch] if rc == 0 else []
        log("cpp: compiling %d programs (%d at a time%s)" % (len(by["cpp"]), jobs, ", precompiled header" if inc else ""))

        def build_cpp(j):
            f = os.path.join(cd, j[0] + ".cpp")
            write(f, j[4])
            exe = os.path.join(cd, j[0])
            return j, run([have["cpp"]] + flags + inc + ["-o", exe, f], timeout=300), exe
        with cf.ThreadPoolExecutor(jobs) as ex:
            for j, (rc2, o2, e2, _), exe in ex.map(build_cpp, by["cpp"]):
                if compiled(j, rc2, o2, e2, exe):
                    to_run.append((j, [exe, "--json"]))
    if by["rust"]:
        rd = os.path.join(work, "rust")
        os.makedirs(rd, exist_ok=True)
        log("rust: compiling %d programs (%d at a time)" % (len(by["rust"]), jobs))

        def build_rs(j):
            f = os.path.join(rd, j[0] + ".rs")
            write(f, j[4])
            exe = os.path.join(rd, j[0])
            return j, run([have["rust"], "-O", "--edition", "2021", "-o", exe, f], timeout=300), exe
        with cf.ThreadPoolExecutor(jobs) as ex:
            for j, (rc2, o2, e2, _), exe in ex.map(build_rs, by["rust"]):
                if compiled(j, rc2, o2, e2, exe):
                    to_run.append((j, [exe, "--json"]))
    for j in by["scala"]:
        sd = os.path.join(work, "scala")
        os.makedirs(sd, exist_ok=True)
        f = os.path.join(sd, j[0] + ".scala")
        write(f, j[4])
        to_run.append((j, [have["scala"], "run", f, "--", "--json"]))
    if to_run:
        log("running %d programs" % len(to_run))
    with cf.ThreadPoolExecutor(jobs) as ex:
        futs = {ex.submit(run, argv, work, timeout if j[2] != "scala" else max(timeout, 120)): j for j, argv in to_run}
        for fu in cf.as_completed(futs):
            rc, out, err, secs = fu.result()
            finish(futs[fu], rc, out, err, secs)
    if not keep:
        shutil.rmtree(work, ignore_errors=True)
    order = {p.get("id"): i for i, p in enumerate(problems)}
    results.sort(key=lambda r: (order.get(r["id"], 0), ALL.index(r["lang"]) if r["lang"] in ALL else -1, r["kind"]))
    return results


PARITY_JS = r"""
const H = require(process.argv[1]), fs = require("fs");
const P = JSON.parse(fs.readFileSync(0, "utf8")), out = {};
for (const p of P) for (const l of H.LANGS) for (const k of ["solution", "starter"]) {
  const c = ((p.langs || {})[l.id] || {})[k];
  if (typeof c !== "string") continue;
  try { out[p.id + "|" + l.id + "|" + k] = H.program(p, l.id, c); } catch (e) { out[p.id + "|" + l.id + "|" + k] = "ERROR " + e.message; }
}
process.stdout.write(JSON.stringify(out));
"""


def js_parity(problems):
    """The browser builds "Copy test program" with web/langharness.js; check it gives exactly the text this checker ran.
    Returns a list of result dicts (status "parity" on a difference); empty when node is not installed."""
    node = shutil.which("node")
    if not node:
        return []
    good = []
    for p in problems:
        try:
            H.prepare(p)
            good.append(p)
        except H.HarnessError:
            pass
    r = subprocess.run([node, "-e", PARITY_JS, H.JS_FILE], input=json.dumps(good), capture_output=True, text=True, timeout=300)
    if r.returncode:
        return [dict(id="-", lang="-", kind="solution", status="parity", detail="node web/langharness.js failed:\n" + short(r.stderr))]
    js, out = json.loads(r.stdout), []
    for p in good:
        for lang in ALL:
            for kind in ("solution", "starter"):
                c = ((p.get("langs") or {}).get(lang) or {}).get(kind)
                if not isinstance(c, str):
                    continue
                k = p["id"] + "|" + lang + "|" + kind
                if js.get(k) != H.program(p, lang, c):
                    a, b = H.program(p, lang, c).splitlines(), (js.get(k) or "").splitlines()
                    n = next((i for i in range(max(len(a), len(b))) if (a[i:i + 1] or [None]) != (b[i:i + 1] or [None])), 0)
                    out.append(dict(id=p["id"], lang=lang, kind=kind, status="parity",
                                    detail="web/langharness.js and tools/langharness.py differ at line %d:\n  py: %s\n  js: %s" % (n + 1, (a[n:n + 1] or ["(end)"])[0][:200], (b[n:n + 1] or ["(end)"])[0][:200])))
    return out


def report(results, langs, verbose=False, out=print):
    """Print a table and the failures; return True when nothing failed."""
    ids = []
    for r in results:
        if r["id"] not in ids:
            ids.append(r["id"])
    w = max([len(str(i)) for i in ids] + [10])
    mark = {"ok": "ok", "fail": "FAIL", "compile": "COMPILE", "timeout": "TIMEOUT", "crash": "CRASH", "sig": "SIG", "missing": "MISSING", "unchecked": "-", "parity": "PARITY"}
    for i in ids:
        rs = [r for r in results if r["id"] == i]
        if any(r["status"] == "sig" for r in rs):
            out("%-*s  SIG ERROR" % (w, i))
            continue
        cells = []
        for l in langs:
            sol = next((r for r in rs if r["lang"] == l and r["kind"] == "solution"), None)
            st = next((r for r in rs if r["lang"] == l and r["kind"] == "starter"), None)
            c = mark[sol["status"]] if sol else "?"
            if sol and sol["status"] in ("ok", "fail") and sol.get("total") is not None:
                c += " %s/%s" % (sol.get("passed"), sol.get("total"))
            if st and st["status"] not in ("ok", "unchecked"):
                c += " (starter " + mark[st["status"]] + ")"
            if any(r["lang"] == l and r["status"] == "parity" for r in rs):
                c += " (PARITY)"
            cells.append("%s %-12s" % (l, c))
        out("%-*s  %s" % (w, i, "  ".join(cells)))
    bad = [r for r in results if r["status"] not in ("ok", "unchecked")]
    for r in bad:
        d = r["detail"] if verbose or r["status"] != "fail" else "\n".join(r["detail"].splitlines()[:3])
        out("\n%s %s %s %s:\n  %s" % (mark[r["status"]], r["id"], r["lang"], r["kind"], d.replace("\n", "\n  ")))
    summ = []
    for l in langs:
        rs = [r for r in results if r["lang"] == l and r["kind"] == "solution"]
        if rs and all(r["status"] == "unchecked" for r in rs):
            summ.append("%s not checked (%s)" % (l, rs[0]["detail"]))
        else:
            summ.append("%s %d/%d" % (l, sum(1 for r in rs if r["status"] == "ok"), len(rs)))
    nsig = len({r["id"] for r in results if r["status"] == "sig"})
    out("\nsolutions passing: " + ", ".join(summ) + ("; %d problem(s) with a bad sig or tests" % nsig if nsig else ""))
    return not bad


def main(argv):
    args = list(argv)

    def opt(name, default=None):
        if name in args:
            i = args.index(name)
            v = args[i + 1]
            del args[i:i + 2]
            return v
        return default
    langs = [l.strip() for l in opt("--langs", ",".join(ALL)).split(",") if l.strip()]
    ids = [x.strip() for x in opt("--ids", "").split(",") if x.strip()]
    jobs = int(opt("--jobs", "0")) or None
    keep = opt("--keep")
    timeout = float(opt("--timeout", "10"))
    starters = "--starters" in args
    verbose = "-v" in args
    args = [a for a in args if a not in ("--starters", "-v")]
    bad = [l for l in langs if l not in ALL]
    if bad or len(args) > 1:
        print(__doc__)
        return 2
    path = args[0] if args else None
    problems = H.load_problems(path)
    if ids:
        missing = [i for i in ids if not any(p.get("id") == i for p in problems)]
        if missing:
            print("unknown ids: " + ", ".join(missing))
            return 2
        problems = [p for p in problems if p.get("id") in ids]
    todo = [p for p in problems if p.get("sig") or p.get("langs")]
    skipped = len(problems) - len(todo)
    if not todo:
        print("no problems with sig and langs to check (%d without)" % skipped)
        return 0
    t0 = time.time()
    res = check(todo, langs, starters=starters, jobs=jobs, keep=keep, timeout=timeout)
    res += js_parity(todo)
    ok = report(res, langs, verbose)
    print("%d problems checked in %.0fs%s" % (len(todo), time.time() - t0, "; %d without sig/langs skipped" % skipped if skipped else ""))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
